/**
 * Розміри деталі варіанту 4 (мм).
 * L  — загальна довжина, B — ширина стояка, H — висота стояка,
 * R1 — зовнішній радіус півкола, R2 — радіус отвору,
 * S  — ширина ребра, T — відступ прихованих ліній від краю стояка.
 */
export const DEFAULT_PARAMS = Object.freeze({ L: 100, B: 30, H: 100, R1: 25, R2: 10, S: 10, T: 10 });

/** @returns {string|null} текст помилки або null, якщо розміри коректні. */
export function validateParams({ L, B, H, R1, R2, S, T }) {
  if ([L, B, H, R1, R2, S].some((v) => !(v > 0))) return 'Усі розміри, крім T, мають бути більшими за 0.';
  if (!(T >= 0)) return 'T не може бути від’ємним.';
  if (R2 >= R1) return 'R2 має бути меншим за R1, інакше отвір виходить за дугу.';
  if (S / 2 >= R1) return 'S має бути меншим за 2·R1, інакше ребро ширше за дугу.';
  if (S >= H) return 'S має бути меншим за H.';
  if (L - B <= R1) return 'L − B має бути більшим за R1, інакше дуга заходить у стояк.';
  return null;
}
