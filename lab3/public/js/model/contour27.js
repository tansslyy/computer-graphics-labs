const pt = ([x, y]) => ({ x, y });

export function contour27() {
  return RAW.map((c) => ({
    name: c.name,
    closed: c.closed,
    tube: c.tube,
    nodes: c.nodes.map(pt),
    ctrl: c.ctrl.map(pt),
    weights: c.ctrl.map(() => [1, c.wB, 1]),
  }));
}

export function cloneContours(list) {
  return list.map((c) => ({
    ...c,
    nodes: c.nodes.map((p) => ({ ...p })),
    ctrl: c.ctrl.map((p) => ({ ...p })),
    weights: c.weights.map((w) => [...w]),
  }));
}
